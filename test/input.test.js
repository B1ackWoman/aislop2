import assert from 'node:assert/strict';
import { GameControls, RemoteControls } from '../src/input.js';

const c = new GameControls();
const neutral = {x:0,z:0,fire:false,jump:false,shield:false,skills:[false,false,false]};
assert.deepEqual(c.read(), neutral);
c.down('KeyW'); c.down('KeyD');
assert.equal(c.read().x, 1); assert.equal(c.read().z, -1);
c.up('KeyW'); c.up('KeyD');
assert.deepEqual(c.read(), neutral, 'Released movement stays neutral');
c.down('KeyW'); c.fire = true; c.down('Space'); c.down('KeyE'); c.down('Digit1');
assert.deepEqual(c.read(false), neutral, 'Menus and non-combat phases cannot control the fighter');
c.clear(); assert.deepEqual(c.read(), neutral, 'Blur and phase transitions release every input');
c.down('Digit2'); c.up('Digit2');
assert.equal(c.read().skills[1], true, 'Very short taps survive until the next simulation/network update');
c.consumeCasts(); assert.deepEqual(c.read(), neutral);
c.down('Digit2', true); assert.deepEqual(c.read(), neutral, 'Keyboard auto-repeat cannot recast');
c.down('ArrowUp'); c.down('Escape'); assert.deepEqual(c.read(), neutral);
c.down('KeyA'); c.down('KeyD'); assert.equal(c.read().x, 0);
c.clear(); c.cast(2); assert.deepEqual(c.read().skills,[false,false,true]);
c.clear(); assert.deepEqual(c.read(), neutral);
const remote = new RemoteControls();
remote.receive({x:1,skills:[true,false,false]},100);
remote.receive({x:0,skills:[false,false,false]},130);
assert.equal(remote.read(140).x,0,'Network movement uses the newest release');
assert.equal(remote.read(140).skills[0],true,'A later neutral packet cannot erase an unconsumed skill tap');
remote.consumeCasts(); assert.deepEqual(remote.read(150).skills,[false,false,false]);
remote.receive({skills:[false,true,false]},160);
remote.receive(neutral,170,true);
assert.deepEqual(remote.read(180).skills,[false,false,false],'Blur explicitly cancels queued remote casts');
remote.receive({x:1,skills:[false,false,true]},190);
assert.deepEqual(remote.read(800),{},'Disconnected input and old casts expire together');
console.log('Input checks passed: release, blur, phase gates, short taps, repeat, opposing keys, HUD casts');
